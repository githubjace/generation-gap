-- Generation Gap: schema + 50 seed questions (10 per generation)
-- Open-ended format: each card has a question, a short answer, and a fun fact.
-- Run this whole file once in the Supabase SQL Editor.

create table if not exists trivia_questions (
  id uuid primary key default gen_random_uuid(),
  generation varchar(20) not null
    check (generation in ('boomer', 'genx', 'millennial', 'genz', 'genalpha')),
  question text not null,
  correct_answer text not null,
  explanation text,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- Index for fast category queries
create index if not exists idx_trivia_generation on trivia_questions(generation);

-- The app only talks to this table from the server using a secret key,
-- so lock it down for everyone else (anon / authenticated keys).
alter table trivia_questions enable row level security;

